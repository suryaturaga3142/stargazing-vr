int sd_init(void) {
    memset(&g_sd_state, 0, sizeof(g_sd_state));
    
    // Store pin configuration from config.h
    g_sd_state.clk_gpio = PIN_SDIO_CLK;
    g_sd_state.cmd_gpio = PIN_SDIO_CMD;
    g_sd_state.d0_gpio = PIN_SDIO_D0;
    g_sd_state.d1_gpio = PIN_SDIO_D0 + 1;
    g_sd_state.d2_gpio = PIN_SDIO_D0 + 2;
    g_sd_state.d3_gpio = PIN_SDIO_D0 + 3;

    if (PIN_SDIO_CLK < 30 || PIN_SDIO_CMD < 30 || PIN_SDIO_D0 < 30) {
        printf("SDIO: All pins must be in the high bank (GPIO >= 30)\n");
        return -1;
    }

    uint32_t reply;
    sdio_status_t status;
    if (!rp2040_sdio_hw_init(calculate_clk_div(SD_INIT_BAUD_RATE))) return -2;
    rp2040_sdio_command_R1(CMD0_GO_IDLE_STATE, 0, NULL);
    status = rp2040_sdio_command_R1(CMD8_SEND_IF_COND, 0x1AA, &reply);
    if (status != SDIO_OK || reply != 0x1AA) {
        printf("SDIO: Card failed CMD8. Not an SDHC card?\n");
        return -3;
    }
    uint32_t start = to_ms_since_boot(get_absolute_time());
    do {
        if (rp2040_sdio_command_R1(CMD55_APP_CMD, 0, &reply) != SDIO_OK ||
            rp2040_sdio_command_R3(ACMD41_SD_SEND_OP_COND, 0xC0100000, &g_sd_state.ocr) != SDIO_OK) {
            printf("SDIO: Failed ACMD41 sequence.\n");
            return -4;
        }
        if ((uint32_t)(to_ms_since_boot(get_absolute_time()) - start) > 1000) {
            printf("SDIO: Init timeout (ACMD41)\n");
            return -5;
        }
    } while (!(g_sd_state.ocr & (1 << 31)));
    uint8_t cid_buffer[16];
    if (rp2040_sdio_command_R2(CMD2_ALL_SEND_CID, 0, cid_buffer) != SDIO_OK) return -6;
    if (rp2040_sdio_command_R1(CMD3_SEND_RELATIVE_ADDR, 0, &g_sd_state.rca) != SDIO_OK) return -7;
    uint8_t csd_buffer[16];
    if (rp2040_sdio_command_R2(CMD9_SEND_CSD, g_sd_state.rca, csd_buffer) != SDIO_OK) return -8;
    if (rp2040_sdio_command_R1(CMD7_SELECT_CARD, g_sd_state.rca, &reply) != SDIO_OK) return -9;
    if (rp2040_sdio_command_R1(CMD55_APP_CMD, g_sd_state.rca, &reply) != SDIO_OK ||
        rp2040_sdio_command_R1(ACMD42_SET_CLR_CARD_DETECT, 0, &reply) != SDIO_OK) return -10;
    if (rp2040_sdio_command_R1(CMD55_APP_CMD, g_sd_state.rca, &reply) != SDIO_OK ||
        rp2040_sdio_command_R1(ACMD6_SET_BUS_WIDTH, 2, &reply) != SDIO_OK) return -11;
    if (!rp2040_sdio_hw_init(calculate_clk_div(SD_BAUD_RATE))) return -12;

    printf("SDIO: Card initialized successfully.\n");
    return 0;
}

int sd_read_blocks(uint32_t sector, uint8_t *buffer, uint32_t num_sectors) {
    // (Function content unchanged)
    if (num_sectors == 0) return 0;
    if (num_sectors > SDIO_MAX_BLOCKS) {
         printf("SDIO: Read request exceeds max blocks (%d)\n", SDIO_MAX_BLOCKS);
        return -1;
    }
    if (((uint32_t)buffer & 3) != 0) {
        printf("SDIO: Read buffer must be 32-bit aligned.\n");
        return -2;
    }
    uint32_t reply;
    uint32_t cmd = (num_sectors > 1) ? CMD18_READ_MULTIPLE_BLOCK : CMD17_READ_SINGLE_BLOCK;
    if (rp2040_sdio_rx_start(buffer, num_sectors) != SDIO_OK ||
        rp2040_sdio_command_R1(cmd, sector, &reply) != SDIO_OK) {
        printf("SDIO: Failed to start read command.\n");
        rp2040_sdio_stop();
        return -3;
    }
    sdio_status_t status;
    do {
        status = rp2040_sdio_rx_poll();
    } while (status == SDIO_BUSY);
    if (status != SDIO_OK) {
        printf("SDIO: Read poll failed.\n");
        sd_sdio_stop_transmission();
        return -4;
    }
    if (num_sectors > 1) {
        if (!sd_sdio_stop_transmission()) {
            printf("SDIO: Failed to stop multi-block read.\n");
            return -5;
        }
    }
    return 0;
}
