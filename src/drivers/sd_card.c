// --- CRC16 ---
__attribute__((optimize("Ofast")))
static uint64_t sdio_crc16_4bit_checksum(uint32_t *data, uint32_t num_words) {
    uint64_t crc = 0;
    uint32_t *end = data + num_words;
    while (data < end) {
        for (int unroll = 0; unroll < 4; unroll++) {
            uint32_t data_in = __builtin_bswap32(*data++);
            uint32_t data_out = crc >> 32;
            crc <<= 32;
            data_out ^= (data_out >> 16);
            data_out ^= (data_in >> 16);
            uint64_t xorred = data_out ^ data_in;
            crc ^= xorred;
            crc ^= xorred << (5 * 4);
            crc ^= xorred << (12 * 4);
        }
    }
    return crc;
}

static void sdio_send_command(uint8_t command, uint32_t arg, uint8_t response_bits) {
    // Note: This function implicitly uses g_sd_state members
    // e.g., pio_sm_clear_fifos(SDIO_PIO, g_sd_state.cmd_sm);
    uint32_t word0 = (47 << 24) | (1 << 22) | (command << 16) | (((arg >> 24) & 0xFF) << 8) | (((arg >> 16) & 0xFF) << 0);
    uint32_t word1 = (((arg >> 8) & 0xFF) << 24) | (((arg >> 0) & 0xFF) << 16) | (1 << 8);
    if (response_bits) { word1 |= ((response_bits - 1) << 0); }
    uint8_t crc = 0;
    crc = crc7_table[crc ^ ((word0 >> 16) & 0xFF)];
    crc = crc7_table[crc ^ ((word0 >> 8) & 0xFF)];
    crc = crc7_table[crc ^ ((word0 >> 0) & 0xFF)];
    crc = crc7_table[crc ^ ((word1 >> 24) & 0xFF)];
    crc = crc7_table[crc ^ ((word1 >> 16) & 0xFF)];
    word1 |= crc << 8;
    pio_sm_clear_fifos(SDIO_PIO, g_sd_state.cmd_sm);
    pio_sm_put(SDIO_PIO, g_sd_state.cmd_sm, word0);
    pio_sm_put(SDIO_PIO, g_sd_state.cmd_sm, word1);
}

static sdio_status_t rp2040_sdio_command_R1(uint8_t command, uint32_t arg, uint32_t *response) {
    sdio_send_command(command, arg, response ? 48 : 0);
    uint32_t start = to_ms_since_boot(get_absolute_time());
    uint32_t wait_words = response ? 2 : 1;
    while (pio_sm_get_rx_fifo_level(SDIO_PIO, g_sd_state.cmd_sm) < wait_words) {
        if ((uint32_t)(to_ms_since_boot(get_absolute_time()) - start) > SD_CMD_TIMEOUT_MS) {
            pio_sm_clear_fifos(SDIO_PIO, g_sd_state.cmd_sm);
            pio_sm_exec(SDIO_PIO, g_sd_state.cmd_sm, pio_encode_jmp(g_sd_state.pio_cmd_clk_offset));
            return g_sd_state.last_error = SDIO_ERR_RESPONSE_TIMEOUT;
        }
    }
    if (response) {
        uint32_t resp0 = pio_sm_get(SDIO_PIO, g_sd_state.cmd_sm);
        uint32_t resp1 = pio_sm_get(SDIO_PIO, g_sd_state.cmd_sm);
        uint8_t crc = 0;
        crc = crc7_table[crc ^ ((resp0 >> 24) & 0xFF)];
        crc = crc7_table[crc ^ ((resp0 >> 16) & 0xFF)];
        crc = crc7_table[crc ^ ((resp0 >> 8) & 0xFF)];
        crc = crc7_table[crc ^ ((resp0 >> 0) & 0xFF)];
        crc = crc7_table[crc ^ ((resp1 >> 8) & 0xFF)];
        uint8_t actual_crc = ((resp1 >> 0) & 0xFE);
        if (crc != actual_crc) return g_sd_state.last_error = SDIO_ERR_RESPONSE_CRC;
        uint8_t response_cmd = ((resp0 >> 24) & 0xFF);
        if (response_cmd != command && command != 41) return g_sd_state.last_error = SDIO_ERR_RESPONSE_CODE;
        *response = ((resp0 & 0xFFFFFF) << 8) | ((resp1 >> 8) & 0xFF);
    } else {
        pio_sm_get(SDIO_PIO, g_sd_state.cmd_sm);
    }
    return g_sd_state.last_error = SDIO_OK;
}

static sdio_status_t rp2040_sdio_command_R2(uint8_t command, uint32_t arg, uint8_t *response) {
    pio_sm_clear_fifos(SDIO_PIO, g_sd_state.cmd_sm);
    uint32_t response_buf[5];
    dma_channel_config dmacfg = dma_channel_get_default_config(g_sd_state.dma_ch_a);
    channel_config_set_transfer_data_size(&dmacfg, DMA_SIZE_32);
    channel_config_set_read_increment(&dmacfg, false);
    channel_config_set_write_increment(&dmacfg, true);
    channel_config_set_dreq(&dmacfg, pio_get_dreq(SDIO_PIO, g_sd_state.cmd_sm, false));
    dma_channel_configure(g_sd_state.dma_ch_a, &dmacfg, &response_buf, &SDIO_PIO->rxf[g_sd_state.cmd_sm], 5, true);
    sdio_send_command(command, arg, 136);
    uint32_t start = to_ms_since_boot(get_absolute_time());
    while (dma_channel_is_busy(g_sd_state.dma_ch_a)) {
        if ((uint32_t)(to_ms_since_boot(get_absolute_time()) - start) > SD_CMD_TIMEOUT_MS) {
            dma_channel_abort(g_sd_state.dma_ch_a);
            pio_sm_clear_fifos(SDIO_PIO, g_sd_state.cmd_sm);
            pio_sm_exec(SDIO_PIO, g_sd_state.cmd_sm, pio_encode_jmp(g_sd_state.pio_cmd_clk_offset));
            return g_sd_state.last_error = SDIO_ERR_RESPONSE_TIMEOUT;
        }
    }
    response[0] = ((response_buf[0] >> 16) & 0xFF);
    response[1] = ((response_buf[0] >> 8) & 0xFF);
    response[2] = ((response_buf[0] >> 0) & 0xFF);
    response[3] = ((response_buf[1] >> 24) & 0xFF);
    response[4] = ((response_buf[1] >> 16) & 0xFF);
    response[5] = ((response_buf[1] >> 8) & 0xFF);
    response[6] = ((response_buf[1] >> 0) & 0xFF);
    response[7] = ((response_buf[2] >> 24) & 0xFF);
    response[8] = ((response_buf[2] >> 16) & 0xFF);
    response[9] = ((response_buf[2] >> 8) & 0xFF);
    response[10] = ((response_buf[2] >> 0) & 0xFF);
    response[11] = ((response_buf[3] >> 24) & 0xFF);
    response[12] = ((response_buf[3] >> 16) & 0xFF);
    response[13] = ((response_buf[3] >> 8) & 0xFF);
    response[14] = ((response_buf[3] >> 0) & 0xFF);
    response[15] = ((response_buf[4] >> 0) & 0xFF);
    return g_sd_state.last_error = SDIO_OK;
}

static sdio_status_t rp2040_sdio_command_R3(uint8_t command, uint32_t arg, uint32_t *response) {
    sdio_send_command(command, arg, 48);
    uint32_t start = to_ms_since_boot(get_absolute_time());
    while (pio_sm_get_rx_fifo_level(SDIO_PIO, g_sd_state.cmd_sm) < 2) {
        if ((uint32_t)(to_ms_since_boot(get_absolute_time()) - start) > SD_CMD_TIMEOUT_MS) {
            pio_sm_clear_fifos(SDIO_PIO, g_sd_state.cmd_sm);
            pio_sm_exec(SDIO_PIO, g_sd_state.cmd_sm, pio_encode_jmp(g_sd_state.pio_cmd_clk_offset));
            return g_sd_state.last_error = SDIO_ERR_RESPONSE_TIMEOUT;
        }
    }
    uint32_t resp0 = pio_sm_get(SDIO_PIO, g_sd_state.cmd_sm);
    uint32_t resp1 = pio_sm_get(SDIO_PIO, g_sd_state.cmd_sm);
    *response = ((resp0 & 0xFFFFFF) << 8) | ((resp1 >> 8) & 0xFF);
    return g_sd_state.last_error = SDIO_OK;
}

static sdio_status_t rp2040_sdio_stop() {
    dma_channel_abort(g_sd_state.dma_ch_a);
    dma_channel_abort(g_sd_state.dma_ch_b);
    pio_sm_set_enabled(SDIO_PIO, g_sd_state.data_sm, false);
    pio_sm_set_consecutive_pindirs(SDIO_PIO, g_sd_state.data_sm, g_sd_state.d0_gpio, 4, false);
    return SDIO_OK;
}

static sdio_status_t rp2040_sdio_rx_start(uint8_t *buffer, uint32_t num_blocks) {
    assert(((uint32_t)buffer & 3) == 0 && num_blocks <= SDIO_MAX_BLOCKS);
    g_sd_state.transfer_start_time = to_ms_since_boot(get_absolute_time());
    g_sd_state.data_buf = (uint32_t*)buffer;
    g_sd_state.blocks_done = 0;
    g_sd_state.total_blocks = num_blocks;
    g_sd_state.blocks_checksumed = 0;
    g_sd_state.checksum_errors = 0;
    for (uint32_t i = 0; i < num_blocks; i++) {
        g_sd_state.dma_blocks[i * 2].write_addr = buffer + i * SD_BLOCK_SIZE;
        g_sd_state.dma_blocks[i * 2].transfer_count = SD_BLOCK_SIZE / sizeof(uint32_t);
        g_sd_state.dma_blocks[i * 2 + 1].write_addr = &g_sd_state.received_checksums[i];
        g_sd_state.dma_blocks[i * 2 + 1].transfer_count = 2;
    }
    g_sd_state.dma_blocks[num_blocks * 2].write_addr = 0;
    g_sd_state.dma_blocks[num_blocks * 2].transfer_count = 0;
    dma_channel_config dmacfg = dma_channel_get_default_config(g_sd_state.dma_ch_a);
    channel_config_set_transfer_data_size(&dmacfg, DMA_SIZE_32);
    channel_config_set_read_increment(&dmacfg, false);
    channel_config_set_write_increment(&dmacfg, true);
    channel_config_set_dreq(&dmacfg, pio_get_dreq(SDIO_PIO, g_sd_state.data_sm, false));
    channel_config_set_bswap(&dmacfg, true);
    channel_config_set_chain_to(&dmacfg, g_sd_state.dma_ch_b);
    dma_channel_configure(g_sd_state.dma_ch_a, &dmacfg, 0, &SDIO_PIO->rxf[g_sd_state.data_sm], 0, false);
    dmacfg = dma_channel_get_default_config(g_sd_state.dma_ch_b);
    channel_config_set_transfer_data_size(&dmacfg, DMA_SIZE_32);
    channel_config_set_read_increment(&dmacfg, true);
    channel_config_set_write_increment(&dmacfg, true);
    channel_config_set_ring(&dmacfg, true, 3);
    dma_channel_configure(g_sd_state.dma_ch_b, &dmacfg, &dma_hw->ch[g_sd_state.dma_ch_a].al1_write_addr, g_sd_state.dma_blocks, 2, false);
    pio_sm_init(SDIO_PIO, g_sd_state.data_sm, g_sd_state.pio_data_rx_offset, &g_sd_state.pio_cfg_data_rx);
    pio_sm_set_consecutive_pindirs(SDIO_PIO, g_sd_state.data_sm, g_sd_state.d0_gpio, 4, false);
    pio_sm_put(SDIO_PIO, g_sd_state.data_sm, (SD_BLOCK_SIZE + 8) * 2 - 1);
    pio_sm_exec(SDIO_PIO, g_sd_state.data_sm, pio_encode_out(pio_y, 32));
    SDIO_PIO->sm[g_sd_state.data_sm].shiftctrl |= PIO_SM0_SHIFTCTRL_FJOIN_RX_BITS;
    dma_channel_start(g_sd_state.dma_ch_b);
    pio_sm_set_enabled(SDIO_PIO, g_sd_state.data_sm, true);
    return g_sd_state.last_error = SDIO_OK;
}

static void sdio_verify_rx_checksums(uint32_t maxcount) {
    while (g_sd_state.blocks_checksumed < g_sd_state.blocks_done && maxcount-- > 0) {
        int blockidx = g_sd_state.blocks_checksumed++;
        uint64_t checksum = sdio_crc16_4bit_checksum(g_sd_state.data_buf + blockidx * (SD_BLOCK_SIZE / 4), (SD_BLOCK_SIZE / 4));
        uint32_t top = __builtin_bswap32(g_sd_state.received_checksums[blockidx].top);
        uint32_t bottom = __builtin_bswap32(g_sd_state.received_checksums[blockidx].bottom);
        uint64_t expected = ((uint64_t)top << 32) | bottom;
        if (checksum != expected) {
            g_sd_state.checksum_errors++;
        }
    }
}

static sdio_status_t rp2040_sdio_rx_poll() {
    bool done = false;
    if (g_sd_state.blocks_done >= g_sd_state.total_blocks) {
        done = true;
    } else {
        sdio_verify_rx_checksums(4);
        uint32_t dma_ctrl_block_count = (dma_hw->ch[g_sd_state.dma_ch_b].read_addr - (uint32_t)&g_sd_state.dma_blocks);
        dma_ctrl_block_count /= sizeof(g_sd_state.dma_blocks[0]);
        g_sd_state.blocks_done = (dma_ctrl_block_count - 1) / 2;
        if (g_sd_state.blocks_done >= g_sd_state.total_blocks) {
            done = true;
        }
    }
    if (done) {
        sdio_verify_rx_checksums(g_sd_state.total_blocks);
        rp2040_sdio_stop();
        if (g_sd_state.checksum_errors > 0) {
            printf("SDIO: %lu checksum errors!\n", g_sd_state.checksum_errors);
            return g_sd_state.last_error = SDIO_ERR_DATA_CRC;
        }
        return g_sd_state.last_error = SDIO_OK;
    }
    if (to_ms_since_boot(get_absolute_time()) - g_sd_state.transfer_start_time >= SD_READ_TIMEOUT_MS) {
        printf("SDIO: Read poll timeout\n");
        rp2040_sdio_stop();
        return g_sd_state.last_error = SDIO_ERR_DATA_TIMEOUT;
    }
    return g_sd_state.last_error = SDIO_BUSY;
}

static bool sd_sdio_stop_transmission() {
    uint32_t reply;
    if (rp2040_sdio_command_R1(CMD12_STOP_TRANSMISSION, 0, &reply) != SDIO_OK) {
        return false;
    }
    uint32_t start = to_ms_since_boot(get_absolute_time());
    while ((sio_hw->gpio_in & (1 << g_sd_state.d0_gpio)) == 0) {
        if (to_ms_since_boot(get_absolute_time()) - start > SD_CMD_TIMEOUT_MS) {
            printf("SDIO: Stop transmission timeout\n");
            return false;
        }
    }
    return true;
}

static float calculate_clk_div(uint baud) {
    float div = (float)clock_get_hz(clk_sys) / (CLKDIV * baud);
    if (div < 1.0) div = 1.0;
    if (div > 65536.0) div = 65536.0;
    return div;
}

static bool rp2040_sdio_hw_init(float clk_div) {
    static bool resources_claimed = false;
    if (!resources_claimed) {
        g_sd_state.cmd_sm = pio_claim_unused_sm(SDIO_PIO, true);
        g_sd_state.data_sm = pio_claim_unused_sm(SDIO_PIO, true);
        g_sd_state.dma_ch_a = dma_claim_unused_channel(true);
        g_sd_state.dma_ch_b = dma_claim_unused_channel(true);
        resources_claimed = true;
    }
    dma_channel_abort(g_sd_state.dma_ch_a);
    dma_channel_abort(g_sd_state.dma_ch_b);
    pio_sm_set_enabled(SDIO_PIO, g_sd_state.cmd_sm, false);
    pio_sm_set_enabled(SDIO_PIO, g_sd_state.data_sm, false);
    pio_clear_instruction_memory(SDIO_PIO);

    g_sd_state.pio_cmd_clk_offset = pio_add_program(SDIO_PIO, &sdio_cmd_clk_program);
    pio_sm_config cfg = sdio_cmd_clk_program_get_default_config(g_sd_state.pio_cmd_clk_offset);
    sm_config_set_out_pins(&cfg, g_sd_state.cmd_gpio, 1);
    sm_config_set_in_pins(&cfg, g_sd_state.cmd_gpio);
    sm_config_set_set_pins(&cfg, g_sd_state.cmd_gpio, 1);
    sm_config_set_jmp_pin(&cfg, g_sd_state.cmd_gpio);
    sm_config_set_sideset_pins(&cfg, g_sd_state.clk_gpio);
    sm_config_set_out_shift(&cfg, false, true, 32);
    sm_config_set_in_shift(&cfg, false, true, 32);
    sm_config_set_clkdiv(&cfg, clk_div);
    sm_config_set_mov_status(&cfg, STATUS_TX_LESSTHAN, 2);
    pio_sm_init(SDIO_PIO, g_sd_state.cmd_sm, g_sd_state.pio_cmd_clk_offset, &cfg);
    pio_sm_set_consecutive_pindirs(SDIO_PIO, g_sd_state.cmd_sm, g_sd_state.clk_gpio, 1, true);
    pio_sm_set_enabled(SDIO_PIO, g_sd_state.cmd_sm, true);

    g_sd_state.pio_data_rx_offset = pio_add_program(SDIO_PIO, &sdio_data_rx_program);
    g_sd_state.pio_cfg_data_rx = sdio_data_rx_program_get_default_config(g_sd_state.pio_data_rx_offset);
    sm_config_set_in_pins(&g_sd_state.pio_cfg_data_rx, g_sd_state.d0_gpio);
    sm_config_set_in_shift(&g_sd_state.pio_cfg_data_rx, false, true, 32);
    sm_config_set_out_shift(&g_sd_state.pio_cfg_data_rx, false, true, 32);
    sm_config_set_clkdiv(&g_sd_state.pio_cfg_data_rx, clk_div);

    uint32_t pin_mask = (1 << (g_sd_state.clk_gpio - 30)) | (1 << (g_sd_state.cmd_gpio - 30)) | (1 << (g_sd_state.d0_gpio - 30)) | (1 << (g_sd_state.d1_gpio - 30)) | (1 << (g_sd_state.d2_gpio - 30)) | (1 << (g_sd_state.d3_gpio - 30));
    SDIO_PIO->input_sync_bypass |= pin_mask;

    gpio_set_function(g_sd_state.cmd_gpio, SDIO_GPIO_FUNC);
    gpio_set_function(g_sd_state.clk_gpio, SDIO_GPIO_FUNC);
    gpio_set_function(g_sd_state.d0_gpio, SDIO_GPIO_FUNC);
    gpio_set_function(g_sd_state.d1_gpio, SDIO_GPIO_FUNC);
    gpio_set_function(g_sd_state.d2_gpio, SDIO_GPIO_FUNC);
    gpio_set_function(g_sd_state.d3_gpio, SDIO_GPIO_FUNC);
    
    gpio_set_slew_rate(g_sd_state.cmd_gpio, GPIO_SLEW_RATE_FAST);
    gpio_set_slew_rate(g_sd_state.clk_gpio, GPIO_SLEW_RATE_FAST);
    gpio_set_slew_rate(g_sd_state.d0_gpio, GPIO_SLEW_RATE_FAST);
    gpio_set_slew_rate(g_sd_state.d1_gpio, GPIO_SLEW_RATE_FAST);
    gpio_set_slew_rate(g_sd_state.d2_gpio, GPIO_SLEW_RATE_FAST);
    gpio_set_slew_rate(g_sd_state.d3_gpio, GPIO_SLEW_RATE_FAST);
    
    gpio_set_drive_strength(g_sd_state.cmd_gpio, GPIO_DRIVE_STRENGTH_8MA);
    gpio_set_drive_strength(g_sd_state.clk_gpio, GPIO_DRIVE_STRENGTH_8MA);
    gpio_set_drive_strength(g_sd_state.d0_gpio, GPIO_DRIVE_STRENGTH_8MA);
    gpio_set_drive_strength(g_sd_state.d1_gpio, GPIO_DRIVE_STRENGTH_8MA);
    gpio_set_drive_strength(g_sd_state.d2_gpio, GPIO_DRIVE_STRENGTH_8MA);
    gpio_set_drive_strength(g_sd_state.d3_gpio, GPIO_DRIVE_STRENGTH_8MA);
    
    return true;
}
